-- ============================================================
-- Create raw.overall
-- Source: Statistics Canada household energy consumption data
-- ============================================================

CREATE TABLE raw.overall (
    raw_id INTEGER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    ref_date INTEGER,
    geo TEXT,
    dguid TEXT,
    energy_type TEXT,
    energy_consumption TEXT,
    uom TEXT,
    uom_id INTEGER,
    scalar_factor TEXT,
    scalar_id INTEGER,
    vector TEXT,
    coordinate TEXT,
    value NUMERIC,
    status TEXT,
    symbol TEXT,
    terminated TEXT,
    decimals INTEGER
);

-- raw_id is generated by PostgreSQL and does not originate
-- from Statistics Canada.
--
-- Source fields remain nullable in the raw layer so unexpected
-- or suppressed source observations can be preserved and
-- investigated rather than rejected during import.
--
-- coordinate is stored as TEXT because values such as 1.3.2
-- are identifiers, not numeric quantities.
--
-- value is stored as NUMERIC because the column contains
-- multiple numeric measures including totals, averages,
-- household counts, and percentages.